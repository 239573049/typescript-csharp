// Shared C# emission layer for all generator scripts (plan/04-codegen.md §1.3).
// Individual generator scripts must NOT embed their own writer variants.

import * as fs from "node:fs";
import * as path from "node:path";

/** Repository root (…/typescript-csharp). Scripts must never depend on cwd. */
export const ROOT: string = path.resolve(import.meta.dirname, "..", "..");

/**
 * Line-buffered code writer: 4-space indentation (repo .editorconfig; the Go side
 * uses tabs), Allman braces via `block`, single trailing newline.
 */
export class CodeWriter {
    private lines: string[] = [];
    private indentLevel: number = 0;

    increaseIndent(): void {
        this.indentLevel++;
    }

    decreaseIndent(): void {
        this.indentLevel--;
    }

    writeLine(line: string = ""): void {
        this.lines.push(line === "" ? "" : "    ".repeat(this.indentLevel) + line);
    }

    /** Writes `header`, then an Allman-style `{ … }` block around `body`. */
    block(header: string, body: () => void, close: string = "}"): void {
        this.writeLine(header);
        this.writeLine("{");
        this.increaseIndent();
        body();
        this.decreaseIndent();
        this.writeLine(close);
    }

    toString(): string {
        return this.lines.join("\n") + "\n";
    }
}

// C# reserved keywords (identifiers needing an @ escape). Contextual keywords
// (value, var, async, …) are legal identifiers and are not escaped — this mirrors
// the Go side's goParamName keyword avoidance (schema.ts:718-720) in spirit.
const CSHARP_KEYWORDS: ReadonlySet<string> = new Set([
    "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char",
    "checked", "class", "const", "continue", "decimal", "default", "delegate",
    "do", "double", "else", "enum", "event", "explicit", "extern", "false",
    "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit",
    "in", "int", "interface", "internal", "is", "lock", "long", "namespace",
    "new", "null", "object", "operator", "out", "override", "params", "private",
    "protected", "public", "readonly", "ref", "return", "sbyte", "sealed",
    "short", "sizeof", "stackalloc", "static", "string", "struct", "switch",
    "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked",
    "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
]);

/** Escapes C# reserved keywords with `@`. JSDoc-bearing names pass through verbatim. */
export function csIdentifier(name: string): string {
    return CSHARP_KEYWORDS.has(name) ? "@" + name : name;
}

/**
 * Produces a C# string literal. All non-ASCII and control characters are emitted
 * as `\uXXXX` escapes so every `.g.cs` file is pure ASCII (plan/04 §1.3).
 */
export function csStringLiteral(s: string): string {
    let out = '"';
    for (let i = 0; i < s.length; i++) {
        const ch = s[i]!;
        const cu = s.charCodeAt(i);
        switch (ch) {
            case '"':
                out += '\\"';
                break;
            case "\\":
                out += "\\\\";
                break;
            case "\n":
                out += "\\n";
                break;
            case "\r":
                out += "\\r";
                break;
            case "\t":
                out += "\\t";
                break;
            default:
                if (cu < 0x20 || cu > 0x7e) {
                    // Per UTF-16 code unit; astral characters become surrogate pairs.
                    out += "\\u" + cu.toString(16).toUpperCase().padStart(4, "0");
                } else {
                    out += ch;
                }
        }
    }
    return out + '"';
}

/**
 * Unified `.g.cs` file header (plan/04 §9.1). No commit hash / timestamp / tool
 * version — regeneration must be idempotent. The explicit `#nullable enable` is
 * required: `<auto-generated>` files opt out of the project nullable context.
 */
export function autoGeneratedHeader(toolName: string, inputs: string[]): string[] {
    return [
        "// <auto-generated>",
        `//     Code generated by tools/generator/${toolName}. DO NOT EDIT.`,
        `//     Inputs: ${inputs.join(", ")}`,
        "// </auto-generated>",
        "#nullable enable",
    ];
}

/**
 * Writes `content` to `filePath` only when it differs (keeps mtime, avoiding
 * pointless rebuilds), then logs the product path and line/byte count.
 */
export function writeIfChanged(filePath: string, content: string | Buffer): void {
    const data: Buffer = typeof content === "string" ? Buffer.from(content, "utf8") : content;
    let unchanged = false;
    if (fs.existsSync(filePath)) {
        unchanged = fs.readFileSync(filePath).equals(data);
    }
    if (!unchanged) {
        fs.mkdirSync(path.dirname(filePath), { recursive: true });
        fs.writeFileSync(filePath, data);
    }
    const rel = path.relative(ROOT, filePath);
    const lineCount = data.toString("utf8").split("\n").length - 1;
    console.log(`${rel}: ${lineCount} lines, ${data.length} bytes${unchanged ? " (unchanged)" : ""}`);
}

/** Reads `tools/generator/expected-counts.json` and returns the named field. */
export function expectedCount(name: string): number {
    const p = path.join(import.meta.dirname, "expected-counts.json");
    const counts = JSON.parse(fs.readFileSync(p, "utf8")) as Record<string, number>;
    const value = counts[name];
    if (typeof value !== "number") {
        throw new Error(`expected-counts.json has no numeric field ${JSON.stringify(name)}`);
    }
    return value;
}

/**
 * Verifies a repo file against its pinned sha256 in UPSTREAM.lock
 * (`sha256.<name> = <hex>`). Input drift without a lock update is an error —
 * upstream bumps go through the plan/04 §10 sync SOP.
 */
export async function verifyUpstreamSha256(lockKey: string, filePath: string): Promise<void> {
    const lock = fs.readFileSync(path.join(ROOT, "UPSTREAM.lock"), "utf8");
    const m = lock.match(new RegExp(`^sha256\\.${lockKey.replaceAll(".", "\\.")}\\s*=\\s*([0-9a-f]{64})\\s*$`, "m"));
    if (!m) {
        throw new Error(`UPSTREAM.lock has no entry sha256.${lockKey}`);
    }
    const crypto = await import("node:crypto");
    const actual = crypto.createHash("sha256").update(fs.readFileSync(filePath)).digest("hex");
    if (actual !== m[1]) {
        throw new Error(
            `sha256 mismatch for ${path.relative(ROOT, filePath)}:\n` +
            `  UPSTREAM.lock sha256.${lockKey} = ${m[1]}\n` +
            `  actual                          = ${actual}\n` +
            `Upstream inputs may only change via the plan/04-codegen.md §10 sync SOP (update UPSTREAM.lock first).`,
        );
    }
}
