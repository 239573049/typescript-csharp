/**
 * Enum stringer generator (plan/04-codegen.md §7): emits explicit ToDisplayString()
 * extension methods for enums whose Go String() output is load-bearing (baseline
 * bytes / fixture formats / wire formats). Declared in stringers.json.
 *
 * Initial roster: Ts.Ast.SyntaxKind only (members derived from ast.json, same input
 * as gen:ast). ModifierFlags-style inline member tables (ModuleKind/ScriptTarget,
 * plan/04 §7.2) join once their hand-written enums land with the core package.
 *
 * Usage: npm run gen:stringers   (node --experimental-strip-types generate-stringers.ts)
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { api } from "./_scripts/schema.ts";
import {
    autoGeneratedHeader,
    CodeWriter,
    ROOT,
    writeIfChanged,
} from "./csharp-emit.ts";

interface StringerEntry {
    enum: string;
    source?: string;
    goTypeName?: string;
    output: string;
}

const entries = JSON.parse(fs.readFileSync(path.join(import.meta.dirname, "stringers.json"), "utf8")) as StringerEntry[];

for (const entry of entries) {
    if (entry.enum !== "Ts.Ast.SyntaxKind" || entry.source !== "ast.json") {
        throw new Error(`generate-stringers.ts: unsupported stringers.json entry ${JSON.stringify(entry.enum)} — inline member tables land with their host enums (plan/04 §7.3)`);
    }
    const goPrefix = entry.goTypeName ?? "Kind";
    const w = new CodeWriter();
    for (const line of autoGeneratedHeader("generate-stringers.ts", ["tools/generator/_scripts/ast.json", "tools/generator/stringers.json"])) {
        w.writeLine(line);
    }
    w.writeLine();
    w.writeLine("using System.Globalization;");
    w.writeLine();
    w.writeLine("namespace Ts.Ast;");
    w.writeLine();
    w.writeLine("// Mirror of the Go stringer for ast.Kind (kind_stringer_generated.go): output is");
    w.writeLine("// fixture/panic-text load-bearing, so member text keeps the Go `Kind` prefix and");
    w.writeLine("// the out-of-range fallback keeps the Go \"Kind(n)\" format (plan/04 §7.2).");
    w.block("public static class SyntaxKindExtensions", () => {
        w.block("public static string ToDisplayString(this SyntaxKind kind) => kind switch", () => {
            // Elements only: markers alias element values and Go's stringer resolves a
            // value to its first (element) name. KindCount is a real distinct value.
            for (const el of api.kindElements()) {
                if (!el.name) continue;
                w.writeLine(`SyntaxKind.${el.name} => "${goPrefix}${el.name}",`);
            }
            w.writeLine(`SyntaxKind.Count => "${goPrefix}Count",`);
            w.writeLine(`_ => "${goPrefix}(" + ((short)kind).ToString(CultureInfo.InvariantCulture) + ")",`);
        }, "};");
    });
    writeIfChanged(path.join(ROOT, entry.output), w.toString());
}

console.log(`gen:stringers: ${entries.length} enum(s)`);
