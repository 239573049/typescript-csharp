// NOT YET PORTED (lands with the localization runtime, plan/04-codegen.md §3.5):
// the 13-locale pipeline generateLocalizations (generate.go:176-338) producing
// Diagnostics/Loc.g.cs + Diagnostics/loc/*.json.gz.
//
// Semantics replicated exactly (plan/04 §3.2/§3.3):
//   - both JSON inputs are indexed by code; same-file code collisions: later key
//     silently wins (generate.go:354-357);
//   - extra messages override main ones BY CODE (maps.Copy, generate.go:94);
//   - merged messages sorted by code ascending (generate.go:97-99);
//   - member names/keys come from convertPropertyName (generate.go:408-460),
//     reproduced rune-for-rune so C# member names equal the Go ones.

import * as fs from "node:fs";
import * as path from "node:path";
import {
    CodeWriter,
    ROOT,
    autoGeneratedHeader,
    csStringLiteral,
    expectedCount,
    verifyUpstreamSha256,
    writeIfChanged,
} from "./csharp-emit.ts";

interface RawDiagnosticMessage {
    category: string;
    code: number;
    reportsUnnecessary?: boolean;
    reportsDeprecated?: boolean;
    // spelling error here is [sic] in Strada (generate.go:36-37)
    elidedInCompatabilityPyramid?: boolean;
}

interface DiagnosticMessage {
    key: string; // the message text, i.e. the JSON property name
    category: string;
    code: number;
    reportsUnnecessary: boolean;
    reportsDeprecated: boolean;
    elidedInCompatibilityPyramid: boolean;
}

const VALID_CATEGORIES: ReadonlySet<string> = new Set(["Warning", "Error", "Suggestion", "Message"]);

// ─── convertPropertyName (generate.go:408-460), replicated rune-for-rune ────────

// Go unicode.IsLetter == Unicode category L*; Go unicode.IsDigit == category Nd
// (decimal digit — deliberately NOT all of \p{N}).
const letterRegexp = /^\p{L}$/u;
const digitRegexp = /^\p{Nd}$/u;
// Go token.IsExported: the first code point is an upper-case letter (category Lu).
const exportedRegexp = /^\p{Lu}/u;
// Go token.IsIdentifier: letters/digits/underscore, first rune not a digit, and not
// a Go keyword. Keywords are all-lowercase, so the isExported assertion below
// subsumes the keyword check. Every name in this set is also a valid C# identifier
// (the C# identifier grammar is a superset).
const identifierRegexp = /^[\p{L}_][\p{L}\p{Nd}_]*$/u;

function convertPropertyName(origName: string, code: number): { varName: string; key: string } {
    let b = "";
    for (const r of origName) { // for…of iterates code points, like Go's range over string
        switch (r) {
            case "*":
                b += "_Asterisk";
                break;
            case "/":
                b += "_Slash";
                break;
            case ":":
                b += "_Colon";
                break;
            default:
                b += letterRegexp.test(r) || digitRegexp.test(r) ? r : "_";
        }
    }

    let varName = b;
    // get rid of all multi-underscores
    varName = varName.replace(/_+/g, "_");
    // remove any leading underscore, unless it is followed by a number.
    varName = varName.replace(/^_+(\D)/, "$1");
    // get rid of all trailing underscores.
    varName = varName.replace(/_$/, "");

    // key = varName truncated to 100 UTF-8 *bytes* (Go: key[:100]), then "_" + code.
    let key = varName;
    const keyBytes = Buffer.from(key, "utf8");
    if (keyBytes.length > 100) {
        if ((keyBytes[100]! & 0xc0) === 0x80) {
            throw new Error(`key truncation would split a multi-byte sequence: ${JSON.stringify(origName)}`);
        }
        key = keyBytes.subarray(0, 100).toString("utf8");
    }
    key = `${key}_${code}`;

    if (!exportedRegexp.test(varName)) {
        varName = (varName.startsWith("_") ? "X" : "X_") + varName;
    }

    if (!identifierRegexp.test(varName) || !exportedRegexp.test(varName)) {
        throw new Error(`failed to convert property name to exported identifier: ${JSON.stringify(origName)}`);
    }

    return { varName, key };
}

// ─── input reading (generate.go:340-361) ────────────────────────────────────────

function readRawMessages(p: string): Map<number, DiagnosticMessage> {
    const rawMessages = JSON.parse(fs.readFileSync(p, "utf8")) as Record<string, RawDiagnosticMessage>;

    // Index by code. Same-file code collisions: the later key silently wins
    // (generate.go:354-357; JSON insertion order stands in for Go's map range).
    const codeToMessage = new Map<number, DiagnosticMessage>();
    for (const [key, m] of Object.entries(rawMessages)) {
        if (!VALID_CATEGORIES.has(m.category)) {
            throw new Error(`unknown category ${JSON.stringify(m.category)} for ${JSON.stringify(key)}`);
        }
        codeToMessage.set(m.code, {
            key,
            category: m.category,
            code: m.code,
            reportsUnnecessary: m.reportsUnnecessary ?? false,
            reportsDeprecated: m.reportsDeprecated ?? false,
            elidedInCompatibilityPyramid: m.elidedInCompatabilityPyramid ?? false,
        });
    }
    return codeToMessage;
}

// ─── main ───────────────────────────────────────────────────────────────────────

const diagnosticMessagesPath = path.join(ROOT, "_submodules", "TypeScript", "src", "compiler", "diagnosticMessages.json");
if (!fs.existsSync(diagnosticMessagesPath)) {
    console.error(`missing ${diagnosticMessagesPath}; run: git submodule update --init`);
    process.exit(1);
}
const extraMessagesPath = path.join(import.meta.dirname, "extraDiagnosticMessages.json");

await verifyUpstreamSha256("diagnosticMessages.json", diagnosticMessagesPath);
await verifyUpstreamSha256("extraDiagnosticMessages.json", extraMessagesPath);

const rawDiagnosticMessages = readRawMessages(diagnosticMessagesPath);
const rawExtraMessages = readRawMessages(extraMessagesPath);

// maps.Copy(rawDiagnosticMessages, rawExtraMessages): extra overrides main by code.
for (const [code, m] of rawExtraMessages) {
    rawDiagnosticMessages.set(code, m);
}

const diagnosticMessages = [...rawDiagnosticMessages.values()].sort((a, b) => a.code - b.code);

const expected = expectedCount("diagnostics");
if (diagnosticMessages.length !== expected) {
    throw new Error(
        `diagnostic message count ${diagnosticMessages.length} != expected ${expected}; ` +
        `on upstream bumps update tools/generator/expected-counts.json first (plan/04 §10)`,
    );
}

// Precompute names once; assert uniqueness (the Go compiler enforces this implicitly
// through duplicate `var` declarations).
const converted = diagnosticMessages.map(m => ({ m, ...convertPropertyName(m.key, m.code) }));
{
    const seen = new Map<string, number>();
    for (const { m, varName } of converted) {
        const prev = seen.get(varName);
        if (prev !== undefined) {
            throw new Error(`duplicate member name ${varName} (codes ${prev} and ${m.code})`);
        }
        seen.set(varName, m.code);
    }
}

const w = new CodeWriter();
for (const line of autoGeneratedHeader("generate-diagnostics.ts", [
    "_submodules/TypeScript/src/compiler/diagnosticMessages.json",
    "tools/generator/extraDiagnosticMessages.json",
])) {
    w.writeLine(line);
}
w.writeLine();
w.writeLine("namespace Ts.Diagnostics;");
w.writeLine();
w.block("public static partial class Diagnostics", () => {
    for (const { m, varName, key } of converted) {
        let args = `code: ${m.code}, category: Category.${m.category}, key: ${csStringLiteral(key)}, text: ${csStringLiteral(m.key)}`;
        // Conditional emission order mirrors generate.go:149-157.
        if (m.reportsUnnecessary) {
            args += ", reportsUnnecessary: true";
        }
        if (m.elidedInCompatibilityPyramid) {
            args += ", elidedInCompatibilityPyramid: true";
        }
        if (m.reportsDeprecated) {
            args += ", reportsDeprecated: true";
        }
        w.writeLine(`public static readonly Message ${varName} = new(${args});`);
    }
    w.writeLine();
    // ≙ keyToMessage (generate.go:162-171). A C# string switch compiles to a hash
    // jump — AOT-safe (plan/04 §3.4).
    w.writeLine("public static Message? KeyToMessage(string key) => key switch");
    w.writeLine("{");
    w.increaseIndent();
    for (const { varName, key } of converted) {
        w.writeLine(`${csStringLiteral(key)} => ${varName},`);
    }
    w.writeLine("_ => null,");
    w.decreaseIndent();
    w.writeLine("};");
});

writeIfChanged(path.join(ROOT, "src", "Ts.Compiler", "Diagnostics", "Messages.g.cs"), w.toString());
console.log(`diagnostics: ${diagnosticMessages.length} messages (expected ${expected})`);
