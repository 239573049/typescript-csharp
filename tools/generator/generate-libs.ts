// gen:libs — ports typescript-go internal/bundled/generate.go to emit
// src/Ts.Compiler/Bundled/libs/*.d.ts (byte-identical to tsgo internal/bundled/libs/)
// and src/Ts.Compiler/Bundled/LibNames.g.cs.
//
// Go's embed_generated.go (108 //go:embed declarations + embeddedContents map +
// libsEntries) has no C# counterpart: the csproj EmbeddedResource glob with
// LogicalName="bundled/libs/%(Filename)%(Extension)" replaces it (plan/07 §5.2).
// The !noembed build variant is deliberately not replicated (plan/04 §4.2).

import * as fs from "node:fs";
import * as path from "node:path";
import {
    CodeWriter,
    ROOT,
    autoGeneratedHeader,
    csStringLiteral,
    expectedCount,
    writeIfChanged,
} from "./csharp-emit.ts";

const libInputDir = path.join(ROOT, "_submodules", "TypeScript", "src", "lib");
const copyrightNoticePath = path.join(ROOT, "_submodules", "TypeScript", "scripts", "CopyrightNotice.txt");
const outputDir = path.join(ROOT, "src", "Ts.Compiler", "Bundled", "libs");

interface Lib {
    target: string; // target relative to the libs output dir
    sources: string[]; // sources relative to src/lib
}

// ─── stripJSONC (generate.go:130-157) — both regexes ported verbatim ────────────

// Match escaped characters, double-quoted strings, single-line comments, and
// multi-line comments.
const reJSONComments = /\\.|"(?:\\.|[^"])*"|\/\/.*|\/\*[\s\S]*?\*\//g;
// Match double-quoted strings (to skip) or trailing commas before ] or }.
// (Go `\s` == [\t\n\f\r ]; spelled out to avoid JS \s Unicode breadth.)
const reTrailingComma = /"(?:\\.|[^"])*"|,[\t\n\f\r ]*([}\]])/g;

// Replaces comments and trailing commas with spaces in JSONC content, producing
// valid JSON. Replacements preserve length/offsets, matching the Go in-place edit.
function stripJSONC(text: string): string {
    text = text.replace(reJSONComments, m =>
        m.startsWith("/") ? m.replace(/[^\n]/g, " ") : m);
    text = text.replace(reTrailingComma, (m, bracket: string | undefined) =>
        bracket === undefined ? m : " " + m.slice(1)); // blank only the comma (b[loc[0]] = ' ')
    return text;
}

// ─── input reading (generate.go:159-206) ────────────────────────────────────────

function readLibs(): Lib[] {
    const libsFile = path.join(libInputDir, "libs.json");
    if (!fs.existsSync(libsFile)) {
        console.error(`missing ${libsFile}; run: git submodule update --init`);
        process.exit(1);
    }

    const meta = JSON.parse(stripJSONC(fs.readFileSync(libsFile, "utf8"))) as {
        libs: string[];
        paths?: Record<string, string>;
    };

    const libs: Lib[] = meta.libs.map(libName => ({
        sources: [libName + ".d.ts"],
        target: meta.paths?.[libName] ?? `lib.${libName}.d.ts`,
    }));

    // strings.Compare — ordinal; lib targets are ASCII, so UTF-16 code unit order
    // coincides with Go's byte order.
    libs.sort((a, b) => (a.target < b.target ? -1 : a.target > b.target ? 1 : 0));
    return libs;
}

// CRLF→LF on raw bytes; latin1 round-trip keeps every byte intact.
function removeCRLF(b: Buffer): Buffer {
    return Buffer.from(b.toString("latin1").replaceAll("\r\n", "\n"), "latin1");
}

function readCopyright(): Buffer {
    return removeCRLF(fs.readFileSync(copyrightNoticePath));
}

// ─── generation (generate.go:39-88) ─────────────────────────────────────────────

function generateLibs(libs: Lib[]): void {
    const copyright = readCopyright();

    // Remove and recreate the libs directory for a clean state (drops libs that
    // upstream deleted).
    fs.rmSync(outputDir, { recursive: true, force: true });
    fs.mkdirSync(outputDir, { recursive: true });

    for (const lib of libs) {
        const parts: Buffer[] = [copyright];
        for (const source of lib.sources) {
            parts.push(Buffer.from("\n", "utf8"));
            parts.push(removeCRLF(fs.readFileSync(path.join(libInputDir, source))));
        }
        fs.writeFileSync(path.join(outputDir, lib.target), Buffer.concat(parts));
    }
    console.log(`${path.relative(ROOT, outputDir)}: ${libs.length} files`);
}

function generateLibList(libs: Lib[]): void {
    const w = new CodeWriter();
    for (const line of autoGeneratedHeader("generate-libs.ts", [
        "_submodules/TypeScript/src/lib/libs.json",
        "_submodules/TypeScript/scripts/CopyrightNotice.txt",
    ])) {
        w.writeLine(line);
    }
    w.writeLine();
    w.writeLine("namespace Ts.Bundled;");
    w.writeLine();
    w.block("public static partial class Bundled", () => {
        w.writeLine("// LibNames is the list of all bundled lib files, sorted by name.");
        w.writeLine("// For the list of libs sorted by load order, use [tsoptions.Libs].");
        w.writeLine("public static readonly string[] LibNames =");
        w.writeLine("[");
        w.increaseIndent();
        for (const lib of libs) {
            w.writeLine(`${csStringLiteral(lib.target)},`);
        }
        w.decreaseIndent();
        w.writeLine("];");
    });

    writeIfChanged(path.join(ROOT, "src", "Ts.Compiler", "Bundled", "LibNames.g.cs"), w.toString());
}

// ─── main ───────────────────────────────────────────────────────────────────────

const libs = readLibs();

const expected = expectedCount("libs");
if (libs.length !== expected) {
    // Assert before RemoveAll so a count mismatch never leaves the tree gutted.
    throw new Error(
        `lib count ${libs.length} != expected ${expected}; ` +
        `on upstream bumps update tools/generator/expected-counts.json first (plan/04 §10)`,
    );
}

generateLibs(libs);
generateLibList(libs);
console.log(`libs: ${libs.length} (expected ${expected})`);
