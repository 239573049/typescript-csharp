// gen:unicode — one-shot transcription of tsgo's generated Unicode tables
// (plan/04-codegen.md §6). NOT part of gen:all: the input is the tsgo repository
// itself (the only script in the pipeline that needs it on disk), so this runs
// only when upstream bumps its Unicode version, i.e. when the two generated Go
// files diff during a plan/04 §10 sync.
//
// Inputs (parsed as text; both are rigid machine output of
// internal/stringutil/_scripts/generate-unicode-data.mts):
//   <tsgo>/internal/stringutil/js_case_generated.go
//   <tsgo>/internal/stringutil/identifier_parts_generated.go
// Outputs:
//   src/Ts.Compiler/StringUtil/JsCase.g.cs
//   src/Ts.Compiler/StringUtil/IdentifierParts.g.cs
//
// Correctness story (plan/04 §6.1): transcription is a pure format change, so the
// parser is total over the table bodies — every data line must match the expected
// grammar and is reconstructed byte-for-byte from the parsed values (parse-back
// assertion). Any format drift upstream fails loudly instead of emitting bad data.
//
// Usage: npm run gen:unicode -- --tsgo /path/to/typescript-go

import * as fs from "node:fs";
import * as path from "node:path";
import { CodeWriter, ROOT, autoGeneratedHeader, csStringLiteral, writeIfChanged } from "./csharp-emit.ts";

// ── CLI ─────────────────────────────────────────────────────────────────────

function tsgoRoot(): string {
    const args = process.argv.slice(2);
    const i = args.indexOf("--tsgo");
    if (i < 0 || i + 1 >= args.length) {
        console.error("usage: npm run gen:unicode -- --tsgo /path/to/typescript-go");
        process.exit(1);
    }
    const root = path.resolve(args[i + 1]!);
    if (!fs.existsSync(path.join(root, "internal", "stringutil"))) {
        console.error(`--tsgo ${root}: internal/stringutil not found; not a typescript-go checkout?`);
        process.exit(1);
    }
    return root;
}

// ── Parsing helpers ─────────────────────────────────────────────────────────

class LineReader {
    readonly file: string;
    readonly lines: string[];
    pos = 0;

    constructor(file: string, text: string) {
        this.file = file;
        this.lines = text.split("\n");
    }

    fail(message: string): never {
        throw new Error(`${this.file}:${this.pos + 1}: ${message}\n  line: ${JSON.stringify(this.lines[this.pos] ?? "<eof>")}`);
    }

    peek(): string | undefined {
        return this.lines[this.pos];
    }

    next(): string {
        const line = this.lines[this.pos];
        if (line === undefined) this.fail("unexpected EOF");
        this.pos++;
        return line;
    }

    expect(exact: string): void {
        const line = this.next();
        if (line !== exact) {
            this.pos--;
            this.fail(`expected ${JSON.stringify(exact)}`);
        }
    }

    /** Advances to the line equal to `exact`, failing at EOF. */
    seek(exact: string): void {
        while (this.pos < this.lines.length) {
            if (this.lines[this.pos] === exact) return;
            this.pos++;
        }
        throw new Error(`${this.file}: marker ${JSON.stringify(exact)} not found`);
    }
}

interface Range {
    lo: number;
    hi: number;
    stride: number;
}

interface RangeTable {
    r16: Range[];
    r32: Range[];
    latinOffset: number;
}

// Go range-table entry, gofmt shape: `\t\t{0x41, 0x5A, 1},`
const RANGE_ENTRY = /^\t\t\{(0x[0-9A-F]+), (0x[0-9A-F]+), (\d+)\},$/;

function parseRangeList(r: LineReader, header: string): Range[] {
    r.expect(`\t${header}`);
    const ranges: Range[] = [];
    while (r.peek() !== "\t},") {
        const line = r.next();
        const m = RANGE_ENTRY.exec(line);
        if (m === null) {
            r.pos--;
            r.fail("range entry does not match expected grammar");
        }
        const range: Range = { lo: parseInt(m[1]!, 16), hi: parseInt(m[2]!, 16), stride: parseInt(m[3]!, 10) };
        // Parse-back assertion: the entry reconstructs byte-for-byte.
        const rebuilt = `\t\t{0x${range.lo.toString(16).toUpperCase()}, 0x${range.hi.toString(16).toUpperCase()}, ${range.stride}},`;
        if (rebuilt !== line) r.fail(`parse-back mismatch: rebuilt ${JSON.stringify(rebuilt)}`);
        ranges.push(range);
    }
    r.expect("\t},");
    return ranges;
}

function parseRangeTable(r: LineReader, name: string): RangeTable {
    r.seek(`var ${name} = &unicode.RangeTable{`);
    r.next();
    const r16 = parseRangeList(r, "R16: []unicode.Range16{");
    const r32 = parseRangeList(r, "R32: []unicode.Range32{");
    const latinLine = r.next();
    const m = /^\tLatinOffset: (\d+),$/.exec(latinLine);
    if (m === null) {
        r.pos--;
        r.fail("expected LatinOffset");
    }
    r.expect("}");
    const table: RangeTable = { r16, r32, latinOffset: parseInt(m[1]!, 10) };
    for (const [part, ranges] of [["R16", r16], ["R32", r32]] as const) {
        const max = part === "R16" ? 0xffff : 0x10ffff;
        let prevHi = -1;
        for (const { lo, hi, stride } of ranges) {
            if (lo > hi || hi > max || stride < 1 || lo <= prevHi) {
                throw new Error(`${r.file}: ${name}.${part}: malformed/unsorted range {0x${lo.toString(16)}, 0x${hi.toString(16)}, ${stride}}`);
            }
            prevHi = hi;
        }
    }
    return table;
}

interface SpecialCasing {
    key: number;
    lower: string;
    upper: string;
    conditionalLower: string;
    condition: "None" | "FinalSigma";
}

// Map entry, dprint/gofmt shape (key padded so values align):
//   `\t0x41:    {lower: "a", upper: "A", condition: specialCasingConditionNone},`
//   `\t0x3A3:   {lower: "σ", upper: "Σ", conditionalLower: "ς", condition: specialCasingConditionFinalSigma},`
const CASING_ENTRY =
    /^\t(0x[0-9A-F]+):( +)\{lower: "((?:\\u[0-9A-F]{4}|\\U[0-9A-F]{8})*)", upper: "((?:\\u[0-9A-F]{4}|\\U[0-9A-F]{8})*)",(?: conditionalLower: "((?:\\u[0-9A-F]{4}|\\U[0-9A-F]{8})*)",)? condition: specialCasingCondition(None|FinalSigma)\},$/;

/** Decodes Go's `\uXXXX` / `\UXXXXXXXX` escapes into a JS (UTF-16) string. */
function decodeGoEscapes(raw: string): string {
    return raw.replaceAll(/\\u([0-9A-F]{4})|\\U([0-9A-F]{8})/g, (_all, u4: string | undefined, u8: string | undefined) => {
        const cp = parseInt((u4 ?? u8)!, 16);
        if (cp > 0x10ffff || (cp >= 0xd800 && cp <= 0xdfff)) {
            throw new Error(`invalid code point in Go escape: ${raw}`);
        }
        return String.fromCodePoint(cp);
    });
}

function parseSpecialCasings(r: LineReader): SpecialCasing[] {
    r.seek("var specialCasingMappings = map[rune]specialCasingMapping{");
    r.next();
    const entries: SpecialCasing[] = [];
    while (r.peek() !== "}") {
        const line = r.next();
        const m = CASING_ENTRY.exec(line);
        if (m === null) {
            r.pos--;
            r.fail("special-casing entry does not match expected grammar");
        }
        const [, key, pad, lower, upper, conditionalLower, condition] = m;
        entries.push({
            key: parseInt(key!, 16),
            lower: decodeGoEscapes(lower!),
            upper: decodeGoEscapes(upper!),
            conditionalLower: conditionalLower === undefined ? "" : decodeGoEscapes(conditionalLower),
            condition: condition as "None" | "FinalSigma",
        });
        // Parse-back assertion (gofmt pads every key to the same column).
        const rebuilt = `\t${key}:${pad}{lower: "${lower}", upper: "${upper}", `
            + (conditionalLower === undefined ? "" : `conditionalLower: "${conditionalLower}", `)
            + `condition: specialCasingCondition${condition}},`;
        if (rebuilt !== line) r.fail(`parse-back mismatch: rebuilt ${JSON.stringify(rebuilt)}`);
    }
    r.expect("}");
    for (let i = 1; i < entries.length; i++) {
        if (entries[i]!.key <= entries[i - 1]!.key) {
            throw new Error(`${r.file}: specialCasingMappings keys not strictly ascending at 0x${entries[i]!.key.toString(16)}`);
        }
    }
    if (!entries.some(e => e.condition === "FinalSigma")) {
        throw new Error(`${r.file}: expected at least one FinalSigma conditional mapping`);
    }
    return entries;
}

/** The `// Code generated …` header comment block of a Go generated file. */
function goHeaderComment(text: string): string[] {
    const out: string[] = [];
    for (const line of text.split("\n")) {
        if (!line.startsWith("//")) break;
        out.push(line);
    }
    return out;
}

// ── Emission ────────────────────────────────────────────────────────────────

const hex4 = (v: number): string => "0x" + v.toString(16).toUpperCase().padStart(4, "0");
const hex6 = (v: number): string => "0x" + v.toString(16).toUpperCase().padStart(6, "0");

function emitRangeTable(w: CodeWriter, csName: string, goName: string, table: RangeTable): void {
    w.writeLine(`// Go: ${goName}.R16 -- {lo, hi, stride} triples, flattened. A ReadOnlySpan<ushort>`);
    w.writeLine("// over a constant array compiles to RVA static data: zero allocation, no cctor");
    w.writeLine("// (plan/07-aot-constraints.md sec. 2).");
    w.block(`internal static ReadOnlySpan<ushort> ${csName}R16 => new ushort[]`, () => {
        for (const { lo, hi, stride } of table.r16) {
            w.writeLine(`${hex4(lo)}, ${hex4(hi)}, ${stride},`);
        }
    }, "};");
    w.writeLine();
    w.writeLine(`// Go: ${goName}.R32.`);
    w.block(`internal static ReadOnlySpan<uint> ${csName}R32 => new uint[]`, () => {
        for (const { lo, hi, stride } of table.r32) {
            w.writeLine(`${hex6(lo)}, ${hex6(hi)}, ${stride},`);
        }
    }, "};");
    w.writeLine();
    w.writeLine(`// Go: ${goName}.LatinOffset. unicode.Is never consults it (only the unexported`);
    w.writeLine("// isExcludingLatin does); transcribed anyway so the C# table is item-for-item");
    w.writeLine("// complete against the Go table.");
    w.writeLine(`internal const int ${csName}LatinOffset = ${table.latinOffset};`);
}

function fileHeader(w: CodeWriter, goFile: string, goHeader: string[]): void {
    for (const line of autoGeneratedHeader("transcribe-unicode.ts", [`typescript-go internal/stringutil/${goFile}`])) {
        w.writeLine(line);
    }
    w.writeLine();
    w.writeLine(`// Header of the transcribed Go file (${goFile}):`);
    for (const line of goHeader) w.writeLine(line);
    w.writeLine();
    w.writeLine("using System;");
    w.writeLine();
    w.writeLine("namespace Ts.StringUtil;");
    w.writeLine();
}

function emitIdentifierParts(start: RangeTable, part: RangeTable, goHeader: string[]): string {
    const w = new CodeWriter();
    fileHeader(w, "identifier_parts_generated.go", goHeader);
    w.block("internal static partial class UnicodeTables", () => {
        emitRangeTable(w, "IdentifierStart", "unicodeESNextIdentifierStart", start);
        w.writeLine();
        emitRangeTable(w, "IdentifierPart", "unicodeESNextIdentifierPart", part);
    });
    return w.toString();
}

function emitJsCase(casings: SpecialCasing[], cased: RangeTable, caseIgnorable: RangeTable, goHeader: string[]): string {
    const w = new CodeWriter();
    fileHeader(w, "js_case_generated.go", goHeader);

    w.writeLine("// Go: type specialCasingCondition uint8 (js_case_generated.go).");
    w.block("internal enum SpecialCasingCondition : byte", () => {
        w.writeLine("None = 0,");
        w.writeLine("FinalSigma = 1,");
    });
    w.writeLine();

    w.block("internal static partial class UnicodeTables", () => {
        w.writeLine("// Go: map[rune]specialCasingMapping (js_case_generated.go) -> parallel arrays in");
        w.writeLine("// strictly ascending key order + binary search (plan/04-codegen.md sec. 6.2): AOT-safe,");
        w.writeLine("// no reflection, no dictionary allocation. Index i of every array below describes");
        w.writeLine("// the same mapping.");
        w.block("internal static ReadOnlySpan<uint> SpecialCasingKeys => new uint[]", () => {
            for (let i = 0; i < casings.length; i += 8) {
                w.writeLine(casings.slice(i, i + 8).map(e => hex6(e.key) + ",").join(" "));
            }
        }, "};");
        w.writeLine();
        w.writeLine("// Go: specialCasingMapping.lower.");
        w.block("internal static readonly string[] SpecialCasingLower = new string[]", () => {
            for (const e of casings) w.writeLine(`${csStringLiteral(e.lower)}, // ${hex6(e.key)}`);
        }, "};");
        w.writeLine();
        w.writeLine("// Go: specialCasingMapping.upper.");
        w.block("internal static readonly string[] SpecialCasingUpper = new string[]", () => {
            for (const e of casings) w.writeLine(`${csStringLiteral(e.upper)}, // ${hex6(e.key)}`);
        }, "};");
        w.writeLine();
        w.writeLine('// Go: specialCasingMapping.conditionalLower ("" when absent, matching the Go zero value).');
        w.block("internal static readonly string[] SpecialCasingConditionalLower = new string[]", () => {
            for (const e of casings) w.writeLine(`${csStringLiteral(e.conditionalLower)}, // ${hex6(e.key)}`);
        }, "};");
        w.writeLine();
        w.writeLine("// Go: specialCasingMapping.condition.");
        w.block("internal static ReadOnlySpan<byte> SpecialCasingConditions => new byte[]", () => {
            for (let i = 0; i < casings.length; i += 16) {
                w.writeLine(casings.slice(i, i + 16).map(e => (e.condition === "None" ? "0," : "1,")).join(" "));
            }
        }, "};");
        w.writeLine();
        emitRangeTable(w, "Cased", "unicodeCasedRanges", cased);
        w.writeLine();
        emitRangeTable(w, "CaseIgnorable", "unicodeCaseIgnorableRanges", caseIgnorable);
    });
    return w.toString();
}

// ── Main ────────────────────────────────────────────────────────────────────

const tsgo = tsgoRoot();
const stringutilDir = path.join(tsgo, "internal", "stringutil");

const identifierPartsText = fs.readFileSync(path.join(stringutilDir, "identifier_parts_generated.go"), "utf8");
const idReader = new LineReader("identifier_parts_generated.go", identifierPartsText);
const identifierStart = parseRangeTable(idReader, "unicodeESNextIdentifierStart");
const identifierPart = parseRangeTable(idReader, "unicodeESNextIdentifierPart");

const jsCaseText = fs.readFileSync(path.join(stringutilDir, "js_case_generated.go"), "utf8");
const jsReader = new LineReader("js_case_generated.go", jsCaseText);
const specialCasings = parseSpecialCasings(jsReader);
const cased = parseRangeTable(jsReader, "unicodeCasedRanges");
const caseIgnorable = parseRangeTable(jsReader, "unicodeCaseIgnorableRanges");

writeIfChanged(
    path.join(ROOT, "src", "Ts.Compiler", "StringUtil", "IdentifierParts.g.cs"),
    emitIdentifierParts(identifierStart, identifierPart, goHeaderComment(identifierPartsText)),
);
writeIfChanged(
    path.join(ROOT, "src", "Ts.Compiler", "StringUtil", "JsCase.g.cs"),
    emitJsCase(specialCasings, cased, caseIgnorable, goHeaderComment(jsCaseText)),
);

const rt = (t: RangeTable): string => `R16×${t.r16.length} R32×${t.r32.length} latinOffset=${t.latinOffset}`;
