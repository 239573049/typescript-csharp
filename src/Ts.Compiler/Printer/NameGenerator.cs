// Ported from tsgo internal/printer/namegenerator.go

using System;
using System.Collections.Generic;
using Ts.Ast;
using Ts.Collections;

namespace Ts.Printer;

using Debug = global::Ts.Core.Debug;

// Flags enum to track count of temp variables and a few dedicated names
internal enum TempFlags
{
    Auto = 0x00000000, // No preferred name
    CountMask = 0x0FFFFFFF, // Temp variable counter
    I = 0x10000000, // Use/preference flag for '_i'
}

public sealed class NameGenerator
{
    public EmitContext? Context;
    public Func<string, bool, bool>? IsFileLevelUniqueNameInCurrentFile; // callback for Printer.isFileLevelUniqueNameInCurrentFile
    public Func<Node, string>? GetTextOfNode; // callback for Printer.getTextOfNode
    private Dictionary<NodeId, string>? nodeIdToGeneratedName; // Map of generated names for specific nodes
    private Dictionary<NodeId, string>? nodeIdToGeneratedPrivateName; // Map of generated private names for specific nodes
    private Dictionary<AutoGenerateId, string>? autoGeneratedIdToGeneratedName; // Map of generated names for temp and loop variables
    private NameGenerationScope? nameGenerationScope;
    private NameGenerationScope? privateNameGenerationScope;
    private Set<string> generatedNames = new(); // NOTE: Used to match Strada, but should be moved to nameGenerationScope after port is complete.

    private sealed class NameGenerationScope
    {
        public NameGenerationScope? Next; // The next nameGenerationScope in the stack
        public TempFlags TempFlags; // TempFlags for the current name generation scope.
        public Dictionary<string, TempFlags>? FormattedNameTempFlags; // TempFlags for the current name generation scope.
        public Set<string> ReservedNames = new(); // Names reserved in nested name generation scopes.
    }

    public void PushScope(bool reuseTempVariableScope)
    {
        privateNameGenerationScope = new NameGenerationScope { Next = privateNameGenerationScope };
        if (!reuseTempVariableScope)
        {
            nameGenerationScope = new NameGenerationScope { Next = nameGenerationScope };
        }
    }

    public void PopScope(bool reuseTempVariableScope)
    {
        if (privateNameGenerationScope is not null)
        {
            privateNameGenerationScope = privateNameGenerationScope.Next;
        }
        if (!reuseTempVariableScope && nameGenerationScope is not null)
        {
            nameGenerationScope = nameGenerationScope.Next;
        }
    }

    // Go: getScope returns **nameGenerationScope. In C# we operate via privateName-keyed
    // getter/setter helpers below rather than pointer-to-pointer.
    private NameGenerationScope? GetScope(bool privateName)
    {
        return privateName ? privateNameGenerationScope : nameGenerationScope;
    }

    private void SetScope(bool privateName, NameGenerationScope scope)
    {
        if (privateName)
        {
            privateNameGenerationScope = scope;
        }
        else
        {
            nameGenerationScope = scope;
        }
    }

    private TempFlags GetTempFlags(bool privateName)
    {
        var scope = GetScope(privateName);
        if (scope is not null)
        {
            return scope.TempFlags;
        }
        return TempFlags.Auto;
    }

    private void SetTempFlags(bool privateName, TempFlags flags)
    {
        var scope = GetScope(privateName);
        if (scope is null)
        {
            scope = new NameGenerationScope();
            SetScope(privateName, scope);
        }
        scope.TempFlags = flags;
    }

    // Gets the TempFlags to use in the current nameGenerationScope for the given key
    private TempFlags GetTempFlagsForFormattedName(bool privateName, string formattedNameKey)
    {
        var scope = GetScope(privateName);
        if (scope is not null && scope.FormattedNameTempFlags is not null && scope.FormattedNameTempFlags.TryGetValue(formattedNameKey, out var flags))
        {
            return flags;
        }
        return TempFlags.Auto;
    }

    // Sets the TempFlags to use in the current nameGenerationScope for the given key
    private void SetTempFlagsForFormattedName(bool privateName, string formattedNameKey, TempFlags flags)
    {
        var scope = GetScope(privateName);
        if (scope is null)
        {
            scope = new NameGenerationScope();
            SetScope(privateName, scope);
        }
        scope.FormattedNameTempFlags ??= new Dictionary<string, TempFlags>();
        scope.FormattedNameTempFlags[formattedNameKey] = flags;
    }

    private void ReserveName(string name, bool privateName, bool scoped, bool temp)
    {
        var scope = GetScope(privateName);
        if (scope is null)
        {
            scope = new NameGenerationScope();
            SetScope(privateName, scope);
        }
        if (privateName || scoped)
        {
            scope.ReservedNames.Add(name);
        }
        else if (!temp)
        {
            generatedNames.Add(name); // NOTE: Matches Strada, but is incorrect.
        }
    }

    // Generate the text for a generated identifier or private identifier
    public string GenerateName(Node name)
    {
        if (Context is not null)
        {
            if (Context.autoGenerate is not null && Context.autoGenerate.TryGetValue(name, out var autoGenerate) && autoGenerate is not null)
            {
                if (autoGenerate.Flags.IsNode())
                {
                    // Node names generate unique names based on their original node
                    // and are cached based on that node's id.
                    return GenerateNameForNodeCached(Context.GetNodeForGeneratedName(name), NodeTests.IsPrivateIdentifier(name), autoGenerate.Flags, autoGenerate.Prefix, autoGenerate.Suffix);
                }
                else
                {
                    // Auto, Loop, and Unique names are cached based on their unique autoGenerateId.
                    if (autoGeneratedIdToGeneratedName is not null && autoGeneratedIdToGeneratedName.TryGetValue(autoGenerate.Id, out var cachedName))
                    {
                        return cachedName;
                    }
                    autoGeneratedIdToGeneratedName ??= new Dictionary<AutoGenerateId, string>();
                    var autoGeneratedName = MakeName(name);
                    autoGeneratedIdToGeneratedName[autoGenerate.Id] = autoGeneratedName;
                    return autoGeneratedName;
                }
            }
        }
        return GetTextOfNode!(name);
    }

    private string GenerateNameForNodeCached(Node node, bool privateName, GeneratedIdentifierFlags flags, string prefix, string suffix)
    {
        var nodeId = global::Ts.Ast.AstUtilities.GetNodeId(node);
        if (privateName)
        {
            nodeIdToGeneratedPrivateName ??= new Dictionary<NodeId, string>();
            if (nodeIdToGeneratedPrivateName.TryGetValue(nodeId, out var cached))
            {
                return cached;
            }
            var name = GenerateNameForNode(node, privateName, flags, prefix, suffix);
            nodeIdToGeneratedPrivateName[nodeId] = name;
            return name;
        }
        else
        {
            nodeIdToGeneratedName ??= new Dictionary<NodeId, string>();
            if (nodeIdToGeneratedName.TryGetValue(nodeId, out var cached))
            {
                return cached;
            }
            var name = GenerateNameForNode(node, privateName, flags, prefix, suffix);
            nodeIdToGeneratedName[nodeId] = name;
            return name;
        }
    }

    private string GenerateNameForNode(Node node, bool privateName, GeneratedIdentifierFlags flags, string prefix, string suffix)
    {
        switch (node.Kind)
        {
            case SyntaxKind.Identifier:
            case SyntaxKind.PrivateIdentifier:
                return MakeUniqueName(GetTextOfNode!(node), null /*checkFn*/, flags.IsOptimistic(), flags.IsReservedInNestedScopes(), privateName, prefix, suffix);
            case SyntaxKind.ModuleDeclaration:
            case SyntaxKind.EnumDeclaration:
                if (privateName || prefix.Length > 0 || suffix.Length > 0)
                {
                    throw new InvalidOperationException("Generated name for a module or enum cannot be private and may have neither a prefix nor suffix");
                }
                return GenerateNameForModuleOrEnum(node);
            case SyntaxKind.ImportDeclaration:
            case SyntaxKind.JSImportDeclaration:
            case SyntaxKind.ExportDeclaration:
                if (privateName || prefix.Length > 0 || suffix.Length > 0)
                {
                    throw new InvalidOperationException("Generated name for an import or export cannot be private and may have neither a prefix nor suffix");
                }
                return GenerateNameForImportOrExportDeclaration(node);
            case SyntaxKind.FunctionDeclaration:
            case SyntaxKind.ClassDeclaration:
            {
                if (privateName || prefix.Length > 0 || suffix.Length > 0)
                {
                    throw new InvalidOperationException("Generated name for a class or function declaration cannot be private and may have neither a prefix nor suffix");
                }
                var name = node.Name();
                if (name is not null && !(Context is null && Context!.HasAutoGenerateInfo(name)))
                {
                    return GenerateNameForNode(name, false /*privateName*/, flags, "" /*prefix*/, "" /*suffix*/);
                }
                return GenerateNameForExportDefault();
            }
            case SyntaxKind.ExportAssignment:
                if (privateName || prefix.Length > 0 || suffix.Length > 0)
                {
                    throw new InvalidOperationException("Generated name for an export assignment cannot be private and may have neither a prefix nor suffix");
                }
                return GenerateNameForExportDefault();
            case SyntaxKind.ClassExpression:
                if (privateName || prefix.Length > 0 || suffix.Length > 0)
                {
                    throw new InvalidOperationException("Generated name for a class expression cannot be private and may have neither a prefix nor suffix");
                }
                return GenerateNameForClassExpression();
            case SyntaxKind.MethodDeclaration:
            case SyntaxKind.GetAccessor:
            case SyntaxKind.SetAccessor:
                return GenerateNameForMethodOrAccessor(node, privateName, prefix, suffix);
            case SyntaxKind.ComputedPropertyName:
                return MakeTempVariableName(TempFlags.Auto, true /*reservedInNestedScopes*/, privateName, prefix, suffix);
            default:
                return MakeTempVariableName(TempFlags.Auto, false /*reservedInNestedScopes*/, privateName, prefix, suffix);
        }
    }

    private string GenerateNameForModuleOrEnum(Node node /* ModuleDeclaration | EnumDeclaration */)
    {
        var name = GetTextOfNode!(node.Name()!);
        // Use module/enum name itself if it is unique, otherwise make a unique variation
        if (PrinterUtilities.IsUniqueLocalName(name, node))
        {
            return name;
        }
        else
        {
            return MakeUniqueName(name, null /*checkFn*/, false /*optimistic*/, false /*scoped*/, false /*privateName*/, "" /*prefix*/, "" /*suffix*/);
        }
    }

    private string GenerateNameForImportOrExportDeclaration(Node node /* ImportDeclaration | ExportDeclaration */)
    {
        var expr = PrinterUtilities.GetExternalModuleName(node);
        var baseName = "module";
        if (expr is not null && NodeTests.IsStringLiteral(expr))
        {
            baseName = Utilities.MakeIdentifierFromModuleName(expr.Text());
        }
        return MakeUniqueName(baseName, null /*checkFn*/, false /*optimistic*/, false /*scoped*/, false /*privateName*/, "" /*prefix*/, "" /*suffix*/);
    }

    private string GenerateNameForExportDefault()
    {
        return MakeUniqueName("default", null /*checkFn*/, false /*optimistic*/, false /*scoped*/, false /*privateName*/, "" /*prefix*/, "" /*suffix*/);
    }

    private string GenerateNameForClassExpression()
    {
        return MakeUniqueName("class", null /*checkFn*/, false /*optimistic*/, false /*scoped*/, false /*privateName*/, "" /*prefix*/, "" /*suffix*/);
    }

    private string GenerateNameForMethodOrAccessor(Node node /* MethodDeclaration | AccessorDeclaration */, bool privateName, string prefix, string suffix)
    {
        if (NodeTests.IsIdentifier(node.Name()!))
        {
            return GenerateNameForNodeCached(node.Name()!, privateName, GeneratedIdentifierFlags.None, prefix, suffix);
        }
        return MakeTempVariableName(TempFlags.Auto, false /*reservedInNestedScopes*/, privateName, prefix, suffix);
    }

    private string MakeName(Node name)
    {
        if (Context is not null)
        {
            if (Context.autoGenerate is not null && Context.autoGenerate.TryGetValue(name, out var autoGenerate) && autoGenerate is not null)
            {
                switch (autoGenerate.Flags.Kind())
                {
                    case GeneratedIdentifierFlags.Auto:
                        return MakeTempVariableName(TempFlags.Auto, autoGenerate.Flags.IsReservedInNestedScopes(), NodeTests.IsPrivateIdentifier(name), autoGenerate.Prefix, autoGenerate.Suffix);
                    case GeneratedIdentifierFlags.Loop:
                        Debug.Assert(NodeTests.IsIdentifier(name));
                        return MakeTempVariableName(TempFlags.I, autoGenerate.Flags.IsReservedInNestedScopes(), false /*privateName*/, autoGenerate.Prefix, autoGenerate.Suffix);
                    case GeneratedIdentifierFlags.Unique:
                        return MakeUniqueName(
                            name.Text(),
                            autoGenerate.Flags.IsFileLevel() ? IsFileLevelUniqueNameInCurrentFile : null,
                            autoGenerate.Flags.IsOptimistic(),
                            autoGenerate.Flags.IsReservedInNestedScopes(),
                            NodeTests.IsPrivateIdentifier(name),
                            autoGenerate.Prefix,
                            autoGenerate.Suffix);
                }
            }
        }
        return GetTextOfNode!(name);
    }

    // Return the next available name in the pattern _a ... _z, _0, _1, ...
    // TempFlags._i may be used to express a preference for that dedicated name.
    // Note that names generated by makeTempVariableName and makeUniqueName will never conflict.
    private string MakeTempVariableName(TempFlags flags, bool reservedInNestedScopes, bool privateName, string prefix, string suffix)
    {
        TempFlags tempFlags;
        string key = "";
        bool simple = prefix.Length == 0 && suffix.Length == 0;
        if (simple)
        {
            tempFlags = GetTempFlags(privateName);
        }
        else
        {
            // Generate a key to use to acquire a TempFlags counter based on the fixed portions of the generated name.
            key = Utilities.FormatGeneratedName(privateName, prefix, "" /*base*/, suffix);
            if (privateName)
            {
                key = Utilities.EnsureLeadingHash(key);
            }
            tempFlags = GetTempFlagsForFormattedName(privateName, key);
        }

        if (flags != 0 && (tempFlags & flags) == 0)
        {
            var fullName = Utilities.FormatGeneratedName(privateName, prefix, "_i", suffix);
            if (IsUniqueName(fullName, privateName))
            {
                tempFlags |= flags;
                ReserveName(fullName, privateName, reservedInNestedScopes, true /*temp*/);
                if (simple)
                {
                    SetTempFlags(privateName, tempFlags);
                }
                else
                {
                    SetTempFlagsForFormattedName(privateName, key, tempFlags);
                }
                return fullName;
            }
        }

        while (true)
        {
            var count = tempFlags & TempFlags.CountMask;
            tempFlags++;
            // Skip over 'i' and 'n'
            if (count != (TempFlags)8 && count != (TempFlags)13)
            {
                string name;
                int countValue = (int)count;
                if (countValue < 26)
                {
                    name = "_" + (char)('a' + (byte)countValue);
                }
                else
                {
                    name = "_" + (countValue - 26).ToString(System.Globalization.CultureInfo.InvariantCulture);
                }
                var fullName = Utilities.FormatGeneratedName(privateName, prefix, name, suffix);
                if (IsUniqueName(fullName, privateName))
                {
                    ReserveName(fullName, privateName, reservedInNestedScopes, true /*temp*/);
                    if (simple)
                    {
                        SetTempFlags(privateName, tempFlags);
                    }
                    else
                    {
                        SetTempFlagsForFormattedName(privateName, key, tempFlags);
                    }
                    return fullName;
                }
            }
        }
    }

    // Generate a name that is unique within the current file and doesn't conflict with any names
    // in global scope. The name is formed by adding an '_n' suffix to the specified base name,
    // where n is a positive integer. Note that names generated by makeTempVariableName and
    // makeUniqueName are guaranteed to never conflict.
    // If `optimistic` is set, the first instance will use 'baseName' verbatim instead of 'baseName_1'
    private string MakeUniqueName(string baseName, Func<string, bool, bool>? checkFn, bool optimistic, bool scoped, bool privateName, string prefix, string suffix)
    {
        baseName = Utilities.RemoveLeadingHash(baseName);
        if (optimistic)
        {
            var optimisticName = Utilities.FormatGeneratedName(privateName, prefix, baseName, suffix);
            if (CheckUniqueName(optimisticName, privateName, checkFn))
            {
                ReserveName(optimisticName, privateName, scoped, false /*temp*/);
                return optimisticName;
            }
        }

        // Find the first unique 'name_n', where n is a positive integer
        if (baseName.Length > 0 && baseName[baseName.Length - 1] != '_')
        {
            baseName += "_";
        }

        int i = 1;
        while (true)
        {
            var fullName = Utilities.FormatGeneratedName(privateName, prefix, baseName + i.ToString(System.Globalization.CultureInfo.InvariantCulture), suffix);
            if (CheckUniqueName(fullName, privateName, checkFn))
            {
                ReserveName(fullName, privateName, scoped, false /*temp*/);
                return fullName;
            }
            i++;
        }
    }

    public string MakeFileLevelOptimisticUniqueName(string name)
    {
        return MakeUniqueName(name, IsFileLevelUniqueNameInCurrentFile, true /*optimistic*/, false /*scoped*/, false /*privateName*/, "" /*prefix*/, "" /*suffix*/);
    }

    private bool CheckUniqueName(string name, bool privateName, Func<string, bool, bool>? checkFn)
    {
        if (checkFn is not null)
        {
            return checkFn(name, privateName);
        }
        else
        {
            return IsUniqueName(name, privateName);
        }
    }

    private bool IsUniqueName(string name, bool privateName)
    {
        return (IsFileLevelUniqueNameInCurrentFile is null || IsFileLevelUniqueNameInCurrentFile(name, privateName)) &&
            !IsReservedName(name, privateName);
    }

    private bool IsReservedName(string name, bool privateName)
    {
        var scope = GetScope(privateName);

        // NOTE: The following matches Strada, but is incorrect.
        if (generatedNames.Has(name))
        {
            return true;
        }

        // TODO: generated names should be scoped after Strada port is complete.

        while (scope is not null)
        {
            if (scope.ReservedNames.Has(name))
            {
                return true;
            }
            scope = scope.Next;
        }
        return false;
    }
}
