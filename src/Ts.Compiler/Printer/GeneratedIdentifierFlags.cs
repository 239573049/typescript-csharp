namespace Ts.Printer;

// PORT-NOTE: Go models this as `type GeneratedIdentifierFlags int` packing a 3-bit "kind"
// (mask 7) together with independent flag bits (1<<3 .. 1<<6). Kept as a single enum; the
// Kind()/Is* value-receiver methods become extension methods below.
public enum GeneratedIdentifierFlags
{
    // Kind

    None = 0, // Not automatically generated.
    Auto = 1, // Automatically generated identifier.
    Loop = 2, // Automatically generated identifier with a preference for '_i'.
    Unique = 3, // Unique name based on the 'text' property.
    Node = 4, // Unique name based on the node in the 'Node' property.
    KindMask = 7, // Mask to extract the kind of identifier from its flags.

    // Flags

    ReservedInNestedScopes = 1 << 3, // Reserve the generated name in nested scopes
    Optimistic = 1 << 4, // First instance won't use '_#' if there's no conflict
    FileLevel = 1 << 5, // Use only the file identifiers list and not generated names to search for conflicts
    AllowNameSubstitution = 1 << 6, // Used by `module.ts` to indicate generated nodes which can have substitutions performed upon them (as they were generated by an earlier transform phase)
}

public static class GeneratedIdentifierFlagsExtensions
{
    public static GeneratedIdentifierFlags Kind(this GeneratedIdentifierFlags f)
    {
        return f & GeneratedIdentifierFlags.KindMask;
    }

    public static bool IsAuto(this GeneratedIdentifierFlags f)
    {
        return f.Kind() == GeneratedIdentifierFlags.Auto;
    }

    public static bool IsLoop(this GeneratedIdentifierFlags f)
    {
        return f.Kind() == GeneratedIdentifierFlags.Loop;
    }

    public static bool IsUnique(this GeneratedIdentifierFlags f)
    {
        return f.Kind() == GeneratedIdentifierFlags.Unique;
    }

    public static bool IsNode(this GeneratedIdentifierFlags f)
    {
        return f.Kind() == GeneratedIdentifierFlags.Node;
    }

    public static bool IsReservedInNestedScopes(this GeneratedIdentifierFlags f)
    {
        return (f & GeneratedIdentifierFlags.ReservedInNestedScopes) != 0;
    }

    public static bool IsOptimistic(this GeneratedIdentifierFlags f)
    {
        return (f & GeneratedIdentifierFlags.Optimistic) != 0;
    }

    public static bool IsFileLevel(this GeneratedIdentifierFlags f)
    {
        return (f & GeneratedIdentifierFlags.FileLevel) != 0;
    }

    public static bool HasAllowNameSubstitution(this GeneratedIdentifierFlags f)
    {
        return (f & GeneratedIdentifierFlags.AllowNameSubstitution) != 0;
    }
}
